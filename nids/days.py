"""
Ground truth for every capture the experiments use.

A Day lists the capture, the attacker address(es), the attack windows and how the day is split into
segments for reporting. Times are local wall-clock times of the CICIDS2017 testbed (ADT = UTC-3);
pcap timestamps are UTC.

  friday     verified against the capture itself (legacy/explore_friday.py)
  wednesday  verified against the capture (explore_day.py, 2026-10-22): each window runs from the first to the
             last second of attacker -> victim traffic of that attack. CIC's schedule (whole minutes) cut
             the end of Slowloris, Slowhttptest and Hulk and ran GoldenEye 3 minutes too long.
  synthetic  realistic_pcap_generator.py; windows are offsets from the first packet
"""
import datetime
import os
from dataclasses import dataclass, field

from nids import pcapng_reader as pr
from nids.paths import DATA, SYNTHETIC_PCAP

ADT = datetime.timezone(datetime.timedelta(hours=-3))


def adt(y, mo, d, h, m, s=0):
    return datetime.datetime(y, mo, d, h, m, s, tzinfo=ADT).timestamp()


@dataclass
class Window:
    name: str
    start: float
    end: float
    in_scope: bool = True   # out-of-scope attacks (e.g. Heartbleed) are neither positives nor false alarms


@dataclass
class Day:
    name: str
    captures: list                      # candidate files, first that exists wins (a .cache is built if missing)
    attackers: set
    windows: list
    targets: set = field(default_factory=set)  # attack victims; a positive second needs attacker -> target
                                               # traffic (172.16.0.1 is a NAT address that also carries
                                               # benign traffic). Empty = any destination.
    segments: list = field(default_factory=lambda: [('all', None)])  # (name, start time of segment or None)
    relative: bool = False              # windows are offsets from the first packet (synthetic data)
    note: str = ''

    def capture(self):
        """Path of a cache for this day, building it from the raw capture on first use."""
        cache = None
        for c in self.captures:
            p = c
            if c.endswith('.cache'):
                cache = p
                if os.path.exists(p):
                    return p
            elif os.path.exists(p):
                if cache is None:
                    return p
                print(f'building {os.path.basename(cache)} from {os.path.basename(c)} (one pass)...', flush=True)
                pr.build_cache(p, cache)
                return cache
        raise FileNotFoundError(f'{self.name}: none of {[os.path.basename(c) for c in self.captures]} found in {DATA} '
                                f'(put the CICIDS2017 capture there, or set NIDS_DATA)')


